        col1, col2, col3 = st.columns(3)

        with col1:
            age = st.number_input(
                "Applicant Age (years)",
                min_value=16,
                max_value=75,
                value=28,
                step=1,
                help="Government schemes typically require a minimum age of 18 years.",
            )
